import string

# Simulated public datasets containing lists of happy and sad words
HAPPY_DATASET = {"happy", "joy", "cheerful", "great", "excellent", "love", "good", "wonderful", "fantastic", "glad", "bright"}
SAD_DATASET = {"sad", "cry", "depressed", "terrible", "bad", "awful", "hate", "miserable", "sorrow", "pain", "angry"}

def number_happy(sentence):
    """Returns the total number of words in 'sentence' that are in the happy words dataset."""
    clean_sentence = sentence.translate(str.maketrans('', '', string.punctuation)).lower()
    words = clean_sentence.split()
    return sum(1 for word in words if word in HAPPY_DATASET)

def number_sad(sentence):
    """Returns the total number of words in 'sentence' that are in the sad words dataset."""
    clean_sentence = sentence.translate(str.maketrans('', '', string.punctuation)).lower()
    words = clean_sentence.split()
    return sum(1 for word in words if word in SAD_DATASET)

def analyze_tone():
    # Ask the user for a string containing a sentence
    sentence = input("Enter a sentence for tone analysis: ")

    # Compute the happiness and sadness level of the sentence
    happy_count = number_happy(sentence)
    sad_count = number_sad(sentence)

    # Print the tone of the sentence by printing the number of happy/sad words
    print(f"\nNumber of happy words: {happy_count}")
    print(f"Number of sad words: {sad_count}")

    # Statement of analysis based on tone levels
    if happy_count > sad_count:
        print("Tone Analysis: Positive (Happy)")
    elif sad_count > happy_count:
        print("Tone Analysis: Negative (Sad)")
    else:
        print("Tone Analysis: Neutral")

if __name__ == "__main__":
    analyze_tone()