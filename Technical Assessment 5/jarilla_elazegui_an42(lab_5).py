from textblob import TextBlob

def main():
    positive_count = 0
    neutral_count = 0
    negative_count = 0

    # Perform the sentiment analysis 10 times
    for i in range(1, 11):
        sentence = input(f"[{i}/10] Enter a sentence: ")
        s = TextBlob(sentence)
        p = s.sentiment.polarity

        # Negative p<0, Neutral p=0, Positive p>0
        if p < 0:
            print("Negative")
            negative_count += 1
        elif p == 0:
            print("Neutral")
            neutral_count += 1
        elif p > 0 and p <= 1:
            print("Positive")
            positive_count += 1

    # Summary of how many sentences are positive, neutral or negative
    print("\n--- Sentiment Summary ---")
    print(f"Positive sentences: {positive_count}")
    print(f"Neutral sentences:  {neutral_count}")
    print(f"Negative sentences: {negative_count}")

if __name__ == "__main__":
    main()